import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { WORKFLOW_VISUAL_PHASES, WORKFLOW_VISUAL_STORIES } from "./workflow-visual-data.mjs";

const root = process.cwd();
const manifestPath = resolve(root, "public/story-v3/manifest.json");
const runtimePath = resolve(root, "src/lib/story-studio/visual-story-v3.ts");
await mkdir(dirname(manifestPath), { recursive: true });

const manifest = {
  project: "workflow",
  version: 3,
  generatedBy: "OpenAI built-in imagegen, one call per asset",
  imageContract: { format: "webp", width: 768, height: 512, minimumAssets: 50, minimumCoreReachable: 20 },
  assets: WORKFLOW_VISUAL_STORIES,
};

const runtimeStories = WORKFLOW_VISUAL_STORIES.map((story) => `  {
    id: ${JSON.stringify(story.id)},
    src: ${JSON.stringify(`/story-v3/${story.file.split("/").at(-1)}`)},
    phase: ${JSON.stringify(story.phase)},
    phaseLabel: ${JSON.stringify(story.phaseLabel)},
    person: ${JSON.stringify(story.person)},
    situation: ${JSON.stringify(story.situation)},
    action: ${JSON.stringify(story.action)},
    productState: ${JSON.stringify(story.productState)},
    outcome: ${JSON.stringify(story.outcome)},
    alt: ${JSON.stringify(story.alt)},
    coreReachable: ${story.coreReachable ? "true" : "false"},
  }`).join(",\n");

const runtime = `// Generated by scripts/build-workflow-visual-story.mjs from the reviewed exact-prompt source.\n` +
  `export type VisualStoryStage = "intake" | "evidence" | "compare" | "confirm" | "deliver" | "revise";\n\n` +
  `export const visualStoryV3Phases = ${JSON.stringify(WORKFLOW_VISUAL_PHASES, null, 2)} as const;\n\n` +
  `export const visualStoryV3 = [\n${runtimeStories}\n] as const;\n`;

await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
await writeFile(runtimePath, runtime, "utf8");
console.log(`Prepared ${manifest.assets.length} workflow visual story records.`);
